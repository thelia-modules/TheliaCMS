namespace TheliaCMS\Media\Admin;

/**
 * One page of the list of the media, and where it stands in what matched.
 */
final readonly class MediaGrid
{
    /**
     * @param list<MediaItem> $items
     */
    public function __construct(
        public array $items,
        public int $total,
        public int $page,
        public int $perPage,
    ) {
    }

    public function pageCount(): int
    {
        return max(1, (int) ceil($this->total / $this->perPage));
    }
}
